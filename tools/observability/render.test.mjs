import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { copyFileSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, it } from 'node:test';
import { ALERTS_FILE, SLO_FILE, alertsFor, budget, render, threshold } from './render-alerts.mjs';

const slo = JSON.parse(readFileSync(SLO_FILE, 'utf8'));

describe('the burn-rate arithmetic', () => {
  it('is the burn rate times what is left of the objective', () => {
    assert.equal(budget(0.995), 0.005);
    assert.equal(threshold(0.995, 14.4), 0.072);
    assert.equal(threshold(0.995, 6), 0.03);
    assert.equal(threshold(0.995, 1), 0.005);
    assert.equal(threshold(0.95, 14.4), 0.72);
    assert.equal(threshold(0.99, 6), 0.06);
  });

  it('spends the budget as the windows say: 14.4x for an hour is about 2% of 28 days, 6x for six hours about 5%, and 1x for the window is the whole of it', () => {
    const hours = 28 * 24;
    for (const [burn, long, share] of [[14.4, 1, 0.02], [6, 6, 0.05]]) assert.equal(Math.round(((burn * long) / hours) * 100) / 100, share, `${burn}x over ${long}h`);
    assert.deepEqual(slo.burnWindows.map((w) => [w.burn, w.long, w.short, w.severity]), [[14.4, '1h', '5m', 'page'], [6, '6h', '30m', 'page'], [1, '3d', '6h', 'ticket']]);
  });
});

describe('the rules rendered from the objectives', () => {
  it('are three burn alerts for each objective, each firing only when the long and the short window both exceed the threshold', () => {
    const rules = alertsFor(slo);
    assert.equal(rules.length, slo.objectives.length * 3 + 2);
    const one = rules.find((rule) => rule.alert === 'SloBurn_availability_1h');
    assert.equal(one.for, '2m');
    assert.deepEqual(one.labels, { severity: 'page', slo: 'availability' });
    const [long, short] = one.expr.split(' and ');
    assert.match(long, /\[1h\]\)\) \/ sum\(rate\(qb_http_requests_total\[1h\]\)\)\) > 0\.072$/u);
    assert.match(short, /\[5m\]\)\) \/ sum\(rate\(qb_http_requests_total\[5m\]\)\)\) > 0\.072$/u);
    assert.ok(!one.expr.includes('$W'));
  });

  it('say how fast the budget is going, what the objective is, and where to look', () => {
    const six = alertsFor(slo).find((rule) => rule.alert === 'SloBurn_write_latency_6h');
    assert.match(six.annotations.summary, /burning 6x too fast over 6h \(and over 30m\)/u);
    assert.match(six.annotations.description, /Objective 95% over 28d \(budget 5%\); this rate spends 5% of the budget in six hours/u);
    assert.equal(six.annotations.runbook, 'docs/DEPLOYMENT.md#watching-it');
  });

  it('are what the committed file holds, and change when an objective does', () => {
    assert.equal(render(slo), readFileSync(ALERTS_FILE, 'utf8'));
    const looser = structuredClone(slo);
    looser.objectives[0].objective = 0.99;
    assert.notEqual(render(looser), render(slo));
    assert.match(render(looser), /> 0\.144 and/u);
  });

  it('label themselves as Tier 2 and as generated, at the head of the file', () => {
    const head = render(slo).split('\n').slice(0, 3).join('\n');
    assert.match(head, /GENERATED by tools\/observability\/render-alerts\.mjs/u);
    assert.match(head, /Tier 2 \(ADR-0013\)/u);
    assert.match(head, /evaluated by nothing/u);
  });
});

describe('the command', () => {
  const script = fileURLToPath(new URL('./render-alerts.mjs', import.meta.url));
  const run = (...args) => spawnSync(process.execPath, [script, ...args], { encoding: 'utf8' });

  it('--check passes on the committed file, and fails, naming the command to run, on one that was edited by hand', () => {
    assert.equal(run('--check').status, 0);
    const copy = join(mkdtempSync(join(tmpdir(), 'qb-alerts-')), 'alerts.yaml');
    copyFileSync(ALERTS_FILE, copy);
    assert.equal(run('--check', '--alerts', copy).status, 0);
    writeFileSync(copy, readFileSync(copy, 'utf8').replace('for: 2m', 'for: 3m'));
    const failed = run('--check', '--alerts', copy);
    assert.equal(failed.status, 1);
    assert.match(failed.stderr, /run node tools\/observability\/render-alerts\.mjs/u);
  });

  it('writes the file it renders when not checking', () => {
    const copy = join(mkdtempSync(join(tmpdir(), 'qb-alerts-')), 'alerts.yaml');
    assert.equal(run('--alerts', copy).status, 0);
    assert.equal(readFileSync(copy, 'utf8'), readFileSync(ALERTS_FILE, 'utf8'));
  });
});

