// Renders the alert rules from the objectives (M8-55): `node tools/observability/render-alerts.mjs` writes infra/observability/alerts.yaml from infra/observability/slo.json, and
// `--check` exits non-zero if the committed file is not what the objectives render to, so the two cannot drift.
//
// TIER 2 (ADR-0013). What is made here is a file in Prometheus' rule format, asserted by parsing. It has never been loaded by Prometheus, no alert in it has fired, and no one is paged.
//
// THE MATH. A service level objective of O over a window leaves an error budget of 1 - O. A *burn rate* B is spending the budget B times faster than it lasts the window. An alert fires when the
// error ratio over a long window exceeds B x (1 - O) AND the same is true over a short window: the long window means it is real and has cost something, the short that it is still happening, so an
// alert resolves soon after the problem does (the multiwindow, multi-burn-rate rules of the Google SRE workbook). The three pairs are in slo.json.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const SLO_FILE = join(here, '../../infra/observability/slo.json');
export const ALERTS_FILE = join(here, '../../infra/observability/alerts.yaml');
/** `--alerts <file>` names another file to write or check, for the test that checks the check. */
const target = () => (process.argv.includes('--alerts') ? process.argv[process.argv.indexOf('--alerts') + 1] : ALERTS_FILE);

export const budget = (objective) => Math.round((1 - objective) * 1e9) / 1e9;
export const threshold = (objective, burn) => Math.round(burn * (1 - objective) * 1e9) / 1e9;
const within = (expression, window) => expression.replaceAll('$W', window);

export function alertsFor(slo) {
  const rules = [];
  for (const objective of slo.objectives) {
    for (const pair of slo.burnWindows) {
      const limit = threshold(objective.objective, pair.burn);
      rules.push({
        alert: `SloBurn_${objective.id.replaceAll('-', '_')}_${pair.long}`,
        expr: `(${within(objective.errorRatio, pair.long)}) > ${limit} and (${within(objective.errorRatio, pair.short)}) > ${limit}`,
        for: pair.for,
        labels: { severity: pair.severity, slo: objective.id },
        annotations: {
          summary: `${objective.name}: the error budget is burning ${pair.burn}x too fast over ${pair.long} (and over ${pair.short})`,
          description: `Objective ${objective.objective * 100}% over ${slo.window} (budget ${budget(objective.objective) * 100}%); this rate spends ${pair.spends}. ${objective.why}`,
          runbook: 'docs/DEPLOYMENT.md#watching-it',
        },
      });
    }
  }
  rules.push({
    alert: 'MetricsAbsent',
    expr: 'absent(qb_http_requests_total) or absent(qb_outbox_depth)',
    for: '5m',
    labels: { severity: 'page', slo: 'availability' },
    annotations: { summary: 'The API\'s metrics are not being scraped, so none of the burn alerts can fire', description: 'Either the scraper cannot reach the API on 127.0.0.1:3000/metrics or the API is down.', runbook: 'docs/DEPLOYMENT.md#watching-it' },
  });
  rules.push({
    alert: 'ProbeAbsent',
    expr: 'absent(qb_probe_success) or (time() - max(qb_probe_last_run_timestamp_seconds)) > 900',
    for: '5m',
    labels: { severity: 'ticket', slo: 'probe' },
    annotations: { summary: 'The synthetic probe has not run in fifteen minutes', description: 'The probe is the check made from outside; without it only the API\'s own account is watched.', runbook: 'docs/DEPLOYMENT.md#watching-it' },
  });
  return rules;
}

const quote = (text) => JSON.stringify(text);
export function render(slo) {
  const lines = [
    '# GENERATED by tools/observability/render-alerts.mjs from infra/observability/slo.json. Do not edit; change the objectives and render again (`--check` fails if they differ).',
    `# ${slo.tierNote}`,
    '# Not loaded by anything, evaluated by nothing, and the receiver of a page does not exist.',
    'groups:',
    '  - name: questionbank-slo-burn',
    '    rules:',
  ];
  for (const rule of alertsFor(slo)) {
    lines.push(`      - alert: ${rule.alert}`, `        expr: ${quote(rule.expr)}`, `        for: ${rule.for}`, '        labels:');
    for (const [key, value] of Object.entries(rule.labels)) lines.push(`          ${key}: ${quote(value)}`);
    lines.push('        annotations:');
    for (const [key, value] of Object.entries(rule.annotations)) lines.push(`          ${key}: ${quote(value)}`);
  }
  return `${lines.join('\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const slo = JSON.parse(readFileSync(SLO_FILE, 'utf8'));
  const text = render(slo);
  if (process.argv.includes('--check')) {
    if (readFileSync(target(), 'utf8') !== text) {
      process.stderr.write('infra/observability/alerts.yaml is not what slo.json renders to; run node tools/observability/render-alerts.mjs\n');
      process.exit(1);
    }
  } else writeFileSync(target(), text);
}
